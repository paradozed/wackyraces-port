import ghidra.app.decompiler.DecompInterface;
import ghidra.app.decompiler.DecompileOptions;
import ghidra.app.decompiler.DecompiledFunction;
import ghidra.program.model.listing.Function;
import ghidra.program.model.listing.FunctionIterator;
import ghidra.program.model.listing.Program;
import ghidra.util.task.ConsoleTaskMonitor;

import java.io.BufferedWriter;
import java.io.FileWriter;
import java.io.IOException;

public class ExportWpcDecomp extends ghidra.app.util.headless.HeadlessScript {
    @Override
    public void run() throws Exception {
        String output = getScriptArgs().length > 0 ? getScriptArgs()[0]
                : "/mnt/dev/decomp-wackyraces/analysis/wpc-ghidra-decomp.c";
        Program program = currentProgram;
        DecompInterface decomp = new DecompInterface();
        DecompileOptions options = new DecompileOptions();
        decomp.setOptions(options);
        decomp.toggleCCode(true);
        decomp.toggleSyntaxTree(false);
        decomp.openProgram(program);

        int total = 0;
        int exported = 0;
        try (BufferedWriter out = new BufferedWriter(new FileWriter(output))) {
            out.write("/* REA/Ghidra static decompilation of WPC.EXE */\n");
            out.write("/* Target: " + program.getExecutablePath() + " */\n");
            out.write("/* Generated by ExportWpcDecomp.java; output is pseudocode, not original source. */\n\n");
            FunctionIterator functions = program.getFunctionManager().getFunctions(true);
            while (functions.hasNext() && !monitor.isCancelled()) {
                Function function = functions.next();
                total++;
                out.write("\n/* " + function.getEntryPoint() + " " + function.getName() + " */\n");
                var result = decomp.decompileFunction(function, 60, new ConsoleTaskMonitor());
                if (result != null && result.decompileCompleted()) {
                    DecompiledFunction df = result.getDecompiledFunction();
                    if (df != null) {
                        out.write(df.getC());
                        out.write("\n");
                        exported++;
                    } else {
                        out.write("/* decompiler returned no C output */\n");
                    }
                } else {
                    out.write("/* decompilation failed: " +
                            (result == null ? "no result" : result.getErrorMessage()) + " */\n");
                }
                if ((total & 127) == 0) {
                    println("Exported " + exported + " functions out of " + total);
                }
            }
            out.write("\n/* Summary: functions_seen=" + total + " functions_exported=" + exported + " */\n");
        } finally {
            decomp.closeProgram();
        }
        println("WPC decompilation written to " + output + " (" + exported + "/" + total + " functions)");
    }
}
