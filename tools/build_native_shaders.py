#!/usr/bin/env python3
"""Rebuild the checked-in Vulkan 1.0 shaders using glslangValidator."""
from pathlib import Path
import struct
import subprocess
import tempfile

root = Path(__file__).resolve().parents[1]
parts = ['// Generated by tools/build_native_shaders.py; do not edit.\n#pragma once\n#include <cstdint>\n']
with tempfile.TemporaryDirectory() as directory:
    for stage in ('vert', 'frag'):
        source = root / f'src/port/shaders/sprite.{stage}'
        output = Path(directory) / f'{stage}.spv'
        subprocess.run(['glslangValidator', '-V', '--target-env', 'vulkan1.0',
                        str(source), '-o', str(output)], check=True)
        subprocess.run(['spirv-val', '--target-env', 'vulkan1.0', str(output)], check=True)
        data = output.read_bytes()
        words = struct.unpack(f'<{len(data)//4}I', data)
        parts.append(f'static const uint32_t wpc_sprite_{stage}[] = {{\n')
        for index in range(0, len(words), 8):
            parts.append('    ' + ', '.join(f'0x{word:08x}' for word in words[index:index+8]) + ',\n')
        parts.append('};\n')
(root / 'src/port/vulkan_shaders.h').write_text(''.join(parts))
